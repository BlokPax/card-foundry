<?php

namespace App\InDesign;

use InvalidArgumentException;

/**
 * Emits the ExtendScript that builds ONE card: open a working copy of the
 * template, attach the prepared single-card CSV as the Data Merge source,
 * show the chosen treatment layer, merge, run the configured wotfLib
 * pipeline stages in order, export a PDF, and close everything — returning
 * a JSON report of every stage's lines/warnings.
 *
 * The pipeline and treatment→layer tables come from config/wotf.php, so the
 * run order is declared data, not buried code. Opts support placeholders:
 * "@csv" (prepared CSV), "@treatment", "@links" (the kit's Links folder).
 */
final class BuildScriptGenerator
{
    /**
     * @param  list<array{step:string,label?:string,opts?:array}>  $pipeline
     * @param  array<string,string>  $treatments  treatment key => layer name
     */
    public function __construct(
        private readonly array $pipeline,
        private readonly array $treatments,
    ) {}

    /**
     * @param  array{kitPath:string,workDoc:string,csvPath:string,outputFile:string,treatment:string,proof:bool,format?:string,exportOptions?:array,serial?:string,serialMax?:string,whiteArt?:string,keywords?:array}  $params
     */
    public function generate(array $params): string
    {
        $treatment = $params['treatment'];

        if (! isset($this->treatments[$treatment])) {
            throw new InvalidArgumentException(
                "Unknown treatment \"{$treatment}\" — expected one of: ".implode(', ', array_keys($this->treatments)).'.',
            );
        }

        $format = strtolower($params['format'] ?? 'pdf');

        if (! in_array($format, ['pdf', 'png'], true)) {
            throw new InvalidArgumentException("Unknown export format \"{$format}\" — expected pdf or png.");
        }

        $keywords = (array) ($params['keywords'] ?? []);

        $stages = array_map(fn (array $stage) => [
            'name' => $stage['step'],
            'opts' => $this->resolveOpts($stage['opts'] ?? [], $params)
                + ($stage['step'] === 'abilityKeywords' ? $this->keywordOpts($keywords) : []),
        ], $this->pipeline);

        // The white-ink knockout plate reads as a black frame on any
        // composite proof; production exports keep it. A per-card white
        // plate resolved from the white directories rides along for the
        // kit to place.
        $stages[] = ['name' => 'whitePlate', 'opts' => array_filter([
            'visible' => ! $params['proof'],
            'art' => $params['whiteArt'] ?? null,
        ], fn ($v) => $v !== null && $v !== '')];

        $js = fn (mixed $value) => json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR);

        $lib = $js(rtrim($params['kitPath'], '/').'/wotfLib.jsxinc');
        $workDoc = $js($params['workDoc']);
        $csv = $js($params['csvPath']);
        $outFile = $js($params['outputFile']);
        $showLayer = $js($this->treatments[$treatment]);
        $allLayers = $js(array_values($this->treatments));
        $stagesJson = $js($stages);
        $exportJs = $this->exportJs($format, $params['exportOptions'] ?? [], $outFile);
        $keywordJs = $this->keywordTableJs($keywords);

        return <<<JSX
        // Generated by Card Foundry — builds one card and returns a JSON report.
        $.global.WOTF_SILENT = true;
        var __prevInteraction = app.scriptPreferences.userInteractionLevel;
        app.scriptPreferences.userInteractionLevel = UserInteractionLevels.NEVER_INTERACT;
        $.evalFile(new File({$lib}));
        {$keywordJs}

        function __toJson(v) {
            if (v === null || v === undefined) return "null";
            var t = typeof v;
            if (t === "number" || t === "boolean") return String(v);
            if (t === "string") {
                return '"' + v.replace(/\\\\/g, "\\\\\\\\").replace(/"/g, '\\\\"')
                    .replace(/\\n/g, "\\\\n").replace(/\\r/g, "\\\\r").replace(/\\t/g, "\\\\t") + '"';
            }
            if (v instanceof Array) {
                var parts = [];
                for (var i = 0; i < v.length; i++) parts.push(__toJson(v[i]));
                return "[" + parts.join(",") + "]";
            }
            var props = [];
            for (var k in v) if (v.hasOwnProperty(k)) props.push(__toJson(k) + ":" + __toJson(v[k]));
            return "{" + props.join(",") + "}";
        }

        var report = { ok: true, stages: [], timings: {} };
        var workDoc = null;
        var merged = null;
        var __t = Date.now();
        function __lap(name) { report.timings[name] = Date.now() - __t; __t = Date.now(); }

        try {
            workDoc = app.open(new File({$workDoc}));
            __lap('open');

            // Exactly one treatment layer visible.
            var layers = {$allLayers};
            var show = {$showLayer};
            for (var i = 0; i < layers.length; i++) {
                var layer = workDoc.layers.itemByName(layers[i]);
                if (layer.isValid) layer.visible = (layers[i] === show);
                else if (layers[i] === show) throw new Error("Treatment layer not found: " + show);
            }

            workDoc.dataMergeProperties.selectDataSource(new File({$csv}));
            workDoc.dataMergeProperties.mergeRecords();
            merged = app.activeDocument;
            if (merged === workDoc) throw new Error("Data merge did not produce a merged document.");
            __lap('merge');

            var stages = {$stagesJson};

            app.doScript(function () {
                for (var s = 0; s < stages.length; s++) {
                    var stage = stages[s];
                    var fn = WOTF.steps[stage.name];
                    if (!fn) {
                        report.stages.push({ name: stage.name, warnings: ["No such step in wotfLib."] });
                        report.ok = false;
                        continue;
                    }
                    var stageStart = Date.now();
                    try {
                        var r = fn(merged, stage.opts || {});
                        // Step warnings ("no feather layer -- skipped") are
                        // advisory: the build continues and exports. Only a
                        // thrown step or an unknown step fails the report.
                        report.stages.push({ name: stage.name, lines: r.lines || [], warnings: r.warnings || [], ms: Date.now() - stageStart });
                    } catch (e) {
                        report.stages.push({ name: stage.name, warnings: ["Threw: " + e.message + (e.line ? " (line " + e.line + ")" : "")], ms: Date.now() - stageStart });
                        report.ok = false;
                    }
                }
            }, ScriptLanguage.JAVASCRIPT, undefined, UndoModes.ENTIRE_SCRIPT, "WOTF card build");
            __lap('stages');

        {$exportJs}
            report.output = {$outFile};
            __lap('export');
        } catch (e) {
            report.ok = false;
            report.error = e.message + (e.line ? " (line " + e.line + ")" : "");
        } finally {
            try { if (merged && merged.isValid) merged.close(SaveOptions.NO); } catch (e) {}
            try { if (workDoc && workDoc.isValid) workDoc.close(SaveOptions.NO); } catch (e) {}
            __lap('close');
            app.scriptPreferences.userInteractionLevel = __prevInteraction;
        }

        __toJson(report);
        JSX;
    }

    private function exportJs(string $format, array $options, string $outFileJs): string
    {
        if ($format === 'png') {
            $ppi = (int) ($options['ppi'] ?? 300);
            $transparent = ! empty($options['transparent']) ? 'true' : 'false';

            return <<<JS
                        app.pngExportPreferences.exportResolution = {$ppi};
                        app.pngExportPreferences.antiAlias = true;
                        app.pngExportPreferences.transparentBackground = {$transparent};
                        try { app.pngExportPreferences.pngQuality = PNGQualityEnum.HIGH; } catch (e) {}
                        try { app.pngExportPreferences.pngExportRange = PNGExportRangeEnum.EXPORT_ALL; } catch (e) {}
                        merged.exportFile(ExportFormat.PNG_FORMAT, new File({$outFileJs}));
            JS;
        }

        $marksJs = $this->marksJs($options);

        $presetJs = '';
        if (! empty($options['preset'])) {
            $preset = json_encode((string) $options['preset'], JSON_THROW_ON_ERROR);

            // An export through a preset uses the preset's own marks/bleed —
            // per-run marks options can't reach into it.
            $conflictJs = $marksJs !== ''
                ? 'report.stages.push({ name: "export", warnings: ["Bleed/marks options ignored: the PDF preset overrides them."] });'
                : '';

            $presetJs = <<<JS
                        try {
                            var __preset = app.pdfExportPresets.itemByName({$preset});
                            if (__preset.isValid) { {$conflictJs} merged.exportFile(ExportFormat.PDF_TYPE, new File({$outFileJs}), false, __preset); __exported = true; }
                            else report.stages.push({ name: "export", warnings: ["PDF preset not found: " + {$preset} + " — used current settings."] });
                        } catch (e) {
                            report.stages.push({ name: "export", warnings: ["PDF preset failed: " + e.message + " — used current settings."] });
                        }
            JS;
        }

        return <<<JS
                    var __exported = false;
        {$presetJs}
                    if (!__exported) {
        {$marksJs}
                        merged.exportFile(ExportFormat.PDF_TYPE, new File({$outFileJs}));
                    }
        JS;
    }

    /**
     * Printer's marks and bleed for a preset-less PDF export. Only options
     * the config actually sets are touched — everything else keeps the
     * user's current export preferences.
     */
    private function marksJs(array $options): string
    {
        $lines = [];

        foreach (['cropMarks', 'registrationMarks'] as $key) {
            if (array_key_exists($key, $options)) {
                $lines[] = 'app.pdfExportPreferences.'.$key.' = '.(! empty($options[$key]) ? 'true' : 'false').';';
            }
        }

        if (array_key_exists('bleed', $options)) {
            $bleed = $options['bleed'];

            if (is_numeric($bleed) && (float) $bleed > 0) {
                // A number is millimetres, applied to all four edges.
                $mm = json_encode(((float) $bleed == (int) $bleed ? (int) $bleed : (float) $bleed).'mm', JSON_THROW_ON_ERROR);
                $lines[] = 'app.pdfExportPreferences.useDocumentBleedWithPdf = false;';
                foreach (['bleedTop', 'bleedBottom', 'bleedInside', 'bleedOutside'] as $edge) {
                    $lines[] = "app.pdfExportPreferences.{$edge} = {$mm};";
                }
            } else {
                $lines[] = 'app.pdfExportPreferences.useDocumentBleedWithPdf = '.(! empty($bleed) ? 'true' : 'false').';';
            }
        }

        return $lines === [] ? '' : implode("\n", array_map(fn ($line) => '                        '.$line, $lines));
    }

    /**
     * When the manifest manages the keyword list, the generated script
     * rewrites wotfLib's KNOWN_KEYWORDS table in place before any stage runs
     * (the exported object is the live one).
     */
    private function keywordTableJs(array $keywords): string
    {
        $known = $keywords['known'] ?? null;

        if (! is_array($known) || $known === []) {
            return '';
        }

        $list = json_encode(array_values($known), JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR);

        return <<<JS
        (function () {
            var list = {$list};
            for (var k in WOTF.KNOWN_KEYWORDS) delete WOTF.KNOWN_KEYWORDS[k];
            for (var i = 0; i < list.length; i++) WOTF.KNOWN_KEYWORDS[list[i]] = true;
        })();
        JS;
    }

    /**
     * Keyword styling options for the abilityKeywords stage. knownKeywords /
     * bareKeywords also ride along for wotfLib versions that read them.
     */
    private function keywordOpts(array $keywords): array
    {
        if ($keywords === []) {
            return [];
        }

        return array_filter([
            'styleDefault' => $keywords['styleDefault'] ?? null,
            'styleWhite' => $keywords['styleWhite'] ?? null,
            'styleBareKeywords' => $keywords['styleBare'] ?? null,
            'knownKeywords' => $keywords['known'] ?? null,
            'bareKeywords' => $keywords['bare'] ?? null,
        ], fn ($v) => $v !== null);
    }

    private function resolveOpts(array $opts, array $params): array
    {
        return array_map(fn ($value) => match ($value) {
            '@csv' => $params['csvPath'],
            '@treatment' => $params['treatment'],
            '@links' => rtrim($params['kitPath'], '/').'/Links/',
            '@serial' => $params['serial'] ?? '01',
            '@serialMax' => $params['serialMax'] ?? '',
            '@white' => $params['whiteArt'] ?? '',
            default => $value,
        }, $opts);
    }
}
